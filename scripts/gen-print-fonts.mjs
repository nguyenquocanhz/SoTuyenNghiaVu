// Generates src/reports/fonts.ts: @font-face rules for Tinos (metric-compatible with Times New Roman,
// SIL OFL 1.1, from @fontsource/tinos) embedded as base64, so printed forms lay out the same on every
// Android device – phones ship without Times New Roman and fall back to wider serif fonts.
// Run: node scripts/gen-print-fonts.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = join(root, 'node_modules', '@fontsource', 'tinos');
const SUBSETS = ['vietnamese', 'latin'];
const VARIANTS = ['400', '700', '400-italic', '700-italic'];

const rules = [];
for (const variant of VARIANTS) {
  const css = readFileSync(join(pkg, `${variant}.css`), 'utf8');
  for (const subset of SUBSETS) {
    // Exact block name: "latin" must not match "latin-ext".
    const name = `tinos-${subset}-${variant.includes('italic') ? variant : `${variant}-normal`}`;
    const block = css.match(new RegExp(`/\\* ${name} \\*/\\s*@font-face \\{([^}]+)\\}`));
    if (!block) throw new Error(`Missing ${subset} in ${variant}.css`);
    const body = block[1];
    const weight = /font-weight:\s*(\d+)/.exec(body)[1];
    const style = /font-style:\s*(\w+)/.exec(body)[1];
    const range = /unicode-range:\s*([^;]+);/.exec(body)[1];
    const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(body)[1];
    const data = readFileSync(join(pkg, 'files', file)).toString('base64');
    rules.push(
      `@font-face{font-family:'Tinos';font-style:${style};font-weight:${weight};font-display:block;src:url(data:font/woff2;base64,${data}) format('woff2');unicode-range:${range};}`,
    );
  }
}

const version = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8')).version;
const out = `/* eslint-disable */
// Generated by scripts/gen-print-fonts.mjs from @fontsource/tinos ${version} (SIL Open Font License 1.1). Do not edit.
export const PRINT_FONT_CSS = ${JSON.stringify(rules.join('\n'))};
`;
writeFileSync(join(root, 'src', 'reports', 'fonts.ts'), out);
console.log(`src/reports/fonts.ts: ${rules.length} faces, ${(out.length / 1024).toFixed(0)} KB`);
